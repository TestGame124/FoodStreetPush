using System.Collections.Generic;
using System.Text;
using LastOrders.Core;
using LastOrders.Data;
using UnityEngine;

namespace LastOrders.Night
{
    /// <summary>What the radio says at dawn.</summary>
    public sealed class ThreatProfile
    {
        /// <summary>Archetypes the player is being warned about.</summary>
        public readonly List<EnemyDefinition> Forecast = new List<EnemyDefinition>();

        /// <summary>True when the broadcast is missing something that will actually turn up.
        /// Roughly one night in six.</summary>
        public bool IsIncomplete;

        /// <summary>The projected wave tier, matching the Heat bar's forecast marker.</summary>
        public int Tier;

        public string Broadcast;
    }

    /// <summary>
    /// The dawn forecast (16.1).
    ///
    /// The player builds against this, which turns adaptation into a decision rather than a
    /// punishment. It only works because the WaveDirector is deterministic: the profile is
    /// generated by asking the director for tonight's plan using the same (day, Heat, seed)
    /// it will be asked again at dusk. The forecast is not a prediction about the wave, it
    /// is a reading of it.
    ///
    /// The deliberate exception: roughly one night in six the broadcast is incomplete -
    /// enough to prevent autopilot, rare enough never to feel cheated. Crucially, a wrong
    /// forecast skews toward ADDITIONAL threat and never toward entirely different threat,
    /// so a player who prepared for Burners is never punished for having done so.
    /// </summary>
    public sealed class ThreatProfileService
    {
        readonly WaveDirector director;
        readonly GameBalanceConfig balance;

        public ThreatProfile Current { get; private set; }

        public ThreatProfileService(WaveDirector director, GameBalanceConfig balance)
        {
            this.director = director;
            this.balance = balance;
        }

        /// <summary>
        /// Builds the forecast from the Heat the day is projected to reach.
        ///
        /// Note the input: yesterday's Heat is the best available estimate at dawn, because
        /// today's has not been earned yet. The forecast is honest about tonight's
        /// composition, not about its size - which is correct, since the size is the part
        /// the player is about to decide by how greedily they trade.
        /// </summary>
        public ThreatProfile Forecast(int day, float projectedHeat)
        {
            WavePlan plan = director.BuildPlan(day, projectedHeat);

            var profile = new ThreatProfile { Tier = plan.Tier };

            foreach (EnemyDefinition enemy in plan.Composition) profile.Forecast.Add(enemy);

            var rng = DeterministicRandom.ForNight(day, Mathf.RoundToInt(projectedHeat),
                                                   balance.campaignSeed, 5150);

            if (profile.Forecast.Count > 1 && rng.Chance(balance.incompleteForecastChance))
            {
                profile.IsIncomplete = true;

                // Something is withheld rather than replaced. The player is told less than
                // the truth, never something contrary to it.
                profile.Forecast.RemoveAt(rng.Range(0, profile.Forecast.Count));
            }

            profile.Broadcast = Compose(plan, profile);
            Current = profile;
            return profile;
        }

        /// <summary>
        /// Assembles the broadcast line. A Named Night's authored text always wins - those
        /// seven lines are the setpiece's entire writing budget and do most of its work.
        /// </summary>
        static string Compose(WavePlan plan, ThreatProfile profile)
        {
            if (plan.NamedNight != null && !string.IsNullOrEmpty(plan.NamedNight.broadcast))
                return plan.NamedNight.broadcast;

            if (profile.Forecast.Count == 0)
                return "Static, then nothing. Quiet on the road tonight.";

            var builder = new StringBuilder("Static, then: ");

            for (int i = 0; i < profile.Forecast.Count; i++)
            {
                EnemyDefinition enemy = profile.Forecast[i];

                string line = !string.IsNullOrEmpty(enemy.description)
                    ? enemy.description
                    : enemy.displayName;

                if (i > 0) builder.Append(" ");
                builder.Append(line);
            }

            return builder.ToString();
        }
    }
}
